/**
 * Remote dialog reopen (2.73): the client end of the direct-GET contract of remote dialog content
 * (`nowo_ui_kit.remote_dialog.direct_get`, docs/USAGE.md "Remote dialog content opened directly").
 *
 * A top-level GET of a marked dialog route is redirected by the server to its owning page with a reopen query
 * (`_dialog[route]=<route>&_dialog[params][…]=…`). On that page the `remote_form_dialog` partial prints, on the
 * <dialog>, its safe list and the target the router generated again:
 *   data-nowo-ui-remote-form-reopen-param   the query parameter name (default `_dialog`)
 *   data-nowo-ui-remote-form-reopen-routes  the route names this dialog may reopen (space separated)
 *   data-nowo-ui-remote-form-reopen-route   the requested route, only when it is in the safe list
 *   data-nowo-ui-remote-form-reopen-url     its URL, generated by the router on the server
 * The query only names a route: the URL opened is never read from it. The route of the query must be in the safe
 * list AND equal the server's route, and the URL must be a same-origin path (sameOriginPath(): no other origin, no
 * `//`, no `javascript:`). Once the dialog opens, the reopen parameter is removed with `history.replaceState`, so the
 * page URL is clean while the dialog is open and after it closes. A dialog reopens at most once per page load.
 */

import { sameOriginPath } from './nowo-ui-remote-form-core';

export const REOPEN_PARAM_ATTR = 'data-nowo-ui-remote-form-reopen-param';
export const REOPEN_ROUTES_ATTR = 'data-nowo-ui-remote-form-reopen-routes';
export const REOPEN_ROUTE_ATTR = 'data-nowo-ui-remote-form-reopen-route';
export const REOPEN_URL_ATTR = 'data-nowo-ui-remote-form-reopen-url';
/** Set on a dialog once a runtime reopened it (the IIFE runtime and a Stimulus peer never both do). */
export const REOPENED_ATTR = 'data-nowo-ui-remote-form-reopened';

const PARAMETER = /^[A-Za-z_][A-Za-z0-9_]{0,63}$/;

/** The reopen query parameter of a dialog, null when the dialog has no (valid) reopen contract. */
export function reopenParameter(dialog: Element): string | null {
  const param = dialog.getAttribute(REOPEN_PARAM_ATTR);
  return param !== null && PARAMETER.test(param) ? param : null;
}

/**
 * The same-origin path to open in `dialog` for the page query `search`, or null: the query must name a route of the
 * dialog's safe list that is also the route the server resolved, and the server's URL must be a same-origin path.
 */
export function reopenTarget(dialog: Element, search: string): string | null {
  const param = reopenParameter(dialog);
  if (param === null) {
    return null;
  }
  const route = new URLSearchParams(search).get(`${param}[route]`);
  if (route === null || route === '') {
    return null;
  }
  const allowed = (dialog.getAttribute(REOPEN_ROUTES_ATTR) ?? '').split(/\s+/).filter((name) => name !== '');
  if (!allowed.includes(route) || dialog.getAttribute(REOPEN_ROUTE_ATTR) !== route) {
    return null;
  }
  return sameOriginPath(dialog.getAttribute(REOPEN_URL_ATTR));
}

/** `href` (same origin) as path + query + hash without the reopen parameter (`<param>` and every `<param>[…]` key). */
export function withoutReopenParameter(href: string, param: string): string {
  const url = new URL(href, window.location.href);
  const keys = [...new Set([...url.searchParams.keys()])];
  for (const key of keys) {
    if (key === param || key.startsWith(`${param}[`)) {
      url.searchParams.delete(key);
    }
  }
  return `${url.pathname}${url.search}${url.hash}`;
}

/**
 * Reopens `dialog` from the page URL when it asks for it: `open(url)` opens the remote form (true when it did). On
 * success the reopen parameter leaves the history entry (`replaceState`, state kept). Returns whether it opened.
 */
export function reopenFromLocation(dialog: Element, open: (url: string) => boolean): boolean {
  if (dialog.hasAttribute(REOPENED_ATTR)) {
    return false;
  }
  const param = reopenParameter(dialog);
  const url = reopenTarget(dialog, window.location.search);
  if (param === null || url === null) {
    return false;
  }
  dialog.setAttribute(REOPENED_ATTR, '');
  if (!open(url)) {
    dialog.removeAttribute(REOPENED_ATTR);
    return false;
  }
  try {
    window.history.replaceState(window.history.state, '', withoutReopenParameter(window.location.href, param));
  } catch {
    // A sandboxed document may refuse history changes: the dialog is open anyway.
  }
  return true;
}

/** The title and focus-return opener for a reopened dialog: a page opener of that dialog and URL, when there is one. */
export function reopenOpener(dialog: Element, url: string): HTMLElement | null {
  if (dialog.id === '') {
    return null;
  }
  for (const opener of document.querySelectorAll<HTMLElement>('[data-nowo-ui-dialog-open][data-nowo-ui-dialog-src]')) {
    if (opener.getAttribute('data-nowo-ui-dialog-open') === dialog.id && sameOriginPath(opener.getAttribute('data-nowo-ui-dialog-src')) === url) {
      return opener;
    }
  }
  return null;
}
