<?php

declare(strict_types=1);

namespace Nowo\UiKitBundle\Form;

use Nowo\UiKitBundle\View\Action;
use Symfony\Component\Form\AbstractType;
use Symfony\Component\Form\Extension\Core\Type\HiddenType;
use Symfony\Component\Form\FormBuilderInterface;
use Symfony\Component\Form\FormConfigBuilder;
use Symfony\Component\Form\FormFactoryInterface;
use Symfony\Component\Form\FormView;
use Symfony\Component\OptionsResolver\OptionsResolver;

/**
 * CSRF-only form of a POST {@see Action} that carries a pre-generated `csrfToken` instead of a `form` (2.18,
 * REQ-TWIG-005): one hidden field named `csrf_field` (default `_token`) holding `csrf_token`, under a nameless root,
 * so the request keeps the 1.x / 2.x contract (`$request->request->get('_token')` + `isCsrfTokenValid()`). The token is
 * generated by the host (the Form's own CSRF protection is off: no second token). Rendered by
 * `partials/_action_form_view.html.twig` through `form_start` / `form_end`; only used when symfony/form is installed.
 *
 * @extends AbstractType<null>
 */
final class ActionCsrfType extends AbstractType
{
    public function buildForm(FormBuilderInterface $builder, array $options): void
    {
        if (null !== $options['csrf_token']) {
            $builder->add($options['csrf_field'], HiddenType::class, ['data' => $options['csrf_token'], 'mapped' => false]);
        }
    }

    public function configureOptions(OptionsResolver $resolver): void
    {
        $resolver->setDefaults([
            'csrf_field' => '_token',
            'csrf_token' => null,
            'csrf_protection' => false,
            'data_class' => null,
        ]);
        $resolver->setAllowedTypes('csrf_field', 'string');
        $resolver->setAllowedTypes('csrf_token', ['null', 'string']);
        $resolver->setAllowedValues('csrf_field', FormConfigBuilder::isValidName(...));
    }

    /**
     * Nameless CSRF-only view of a POST action (`csrfToken` in `csrfField`); null when the field name is not a valid
     * form name (such an action keeps the deprecated raw fallback).
     */
    public static function createActionView(FormFactoryInterface $factory, Action $action): ?FormView
    {
        if (!FormConfigBuilder::isValidName($action->csrfField)) {
            return null;
        }

        return $factory->createNamed('', self::class, null, [
            'csrf_field' => $action->csrfField,
            'csrf_token' => $action->csrfToken,
        ])->createView();
    }
}
