<?php

declare(strict_types=1);

namespace Nowo\UiKitBundle\Form;

use Symfony\Component\Form\AbstractType;
use Symfony\Component\Form\Extension\Core\Type\HiddenType;
use Symfony\Component\Form\FormBuilderInterface;
use Symfony\Component\OptionsResolver\OptionsResolver;

/**
 * Hidden-only form of the UiKit partials (2.19, REQ-TWIG-005): one hidden field per entry of `fields` (name => value),
 * nested arrays become compound children so `filter[status]` keeps its query / POST name under a nameless root.
 * `null` / `false` values are skipped and `true` is sent as `1` (the 2.x raw markup did the same). The Form's own
 * CSRF protection is off: a CSRF token generated by the host is just one more hidden field (`_token`,
 * `_csrf_token`…), so controllers keep `isCsrfTokenValid()`. Built by {@see UiFormViews}; rendered with the
 * `nowo_ui_hidden_fields` blocks of `form/nowo_ui_kit_fields.html.twig` (no wrapper, no id on hidden inputs).
 *
 * @extends AbstractType<null>
 */
final class HiddenFieldsType extends AbstractType
{
    public function buildForm(FormBuilderInterface $builder, array $options): void
    {
        /** @var array<array-key, mixed> $fields */
        $fields = $options['fields'];
        foreach ($fields as $name => $value) {
            if (\is_array($value)) {
                $builder->add((string) $name, self::class, ['fields' => $value]);
            } elseif (true === $value) {
                $builder->add((string) $name, HiddenType::class, ['data' => '1', 'mapped' => false]);
            } elseif (\is_scalar($value) && false !== $value || $value instanceof \Stringable) {
                $builder->add((string) $name, HiddenType::class, ['data' => (string) $value, 'mapped' => false]);
            }
        }
    }

    public function configureOptions(OptionsResolver $resolver): void
    {
        $resolver->setDefaults([
            'fields' => [],
            'csrf_protection' => false,
            'data_class' => null,
            'label' => false,
            'required' => false,
            'translation_domain' => false,
        ]);
        $resolver->setAllowedTypes('fields', 'array');
    }

    public function getBlockPrefix(): string
    {
        return 'nowo_ui_hidden_fields';
    }
}
