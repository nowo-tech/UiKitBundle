<?php

declare(strict_types=1);

namespace Nowo\UiKitBundle\Dialog;

/**
 * 2.74: resolves the owning page of remote dialog content when its route parameters come from the record, not from
 * the dialog route (`nowo_ui_kit.remote_dialog.direct_get.routes.<route>.page_resolver: <service id>`). Example: a
 * working-time correction dialog `{uuid}` whose owning page is the day `{uuid}` the correction belongs to.
 *
 * It is called by the direct-GET redirect only, on `kernel.response`, for a `200` HTML answer of a request whose
 * controller ran without an exception (not a streamed answer). That is not proof that the user may see the record (a
 * host may answer `200` to a denial, or check lazily): **the resolver must check access to the record itself** (e.g.
 * `isGranted('VIEW', $record)`) and return null otherwise (audit ZBD-L1). The returned `params` are merged over the mapped `page_parameters` and the
 * `page_defaults` of the entry, and the page URL is generated by the router. Return null to make no redirect: the
 * route keeps its own answer, exactly as when the page link cannot be generated (no existence oracle). An exception
 * thrown here is caught and treated like null.
 *
 * Implementations must be read-only and stateless between requests (FrankenPHP worker mode, kernel not reset): resolve
 * per call, keep no request, user or record in properties.
 */
interface RemoteDialogPageResolverInterface
{
    /**
     * @param string                $route  the dialog content route (the marked route)
     * @param array<string, string> $params its route parameters, as strings
     *
     * @return array{route: string, params: array<string, string|int>}|null the owning page route (must be the entry's
     *                                                                      `page`) and its parameters, or null for no
     *                                                                      redirect
     */
    public function resolve(string $route, array $params): ?array;
}
